'use server'
import { createClient } from '@/lib/supabase/server'
import type {
  IntakeDeliveryInput,
  AdjustStockInput,
  TransferPinInput,
} from '@/lib/validations/inventory'

/**
 * Sum all transaction quantities for a PIN to get current stock level.
 */
async function getCurrentStock(sb: any, pinId: string): Promise<number> {
  const { data } = await sb
    .from('inventory_transactions')
    .select('quantity')
    .eq('pin_id', pinId)
  return (data ?? []).reduce(
    (sum: number, t: any) => sum + (t.quantity ?? 0),
    0
  )
}

/**
 * Intake accepted items from a QC-passed/conditional delivery into inventory.
 * Creates a new PIN per item (pin_number auto-generated by trigger) and
 * records a receipt transaction. Closes the delivery on completion.
 */
export async function dbIntakeDelivery(
  input: IntakeDeliveryInput,
  operatorId: string
) {
  const sb = await createClient()
  const createdPins: any[] = []

  // Find the vendor for the delivery to link to the new PINs
  const { data: dlv, error: dlvErr } = await sb
    .from('deliveries')
    .select('po_id, purchase_orders(vendor_id)')
    .eq('id', input.delivery_id)
    .single()
  
  const vendor_id = (dlv as any)?.purchase_orders?.vendor_id || null;

  for (const item of input.items) {
    // 1. Create PIN (pin_number auto-generated by trigger)
    const { data: pin, error: pinErr } = await sb
      .from('inventory_pins')
      .insert({
        description: item.description,
        part_number: item.part_number ?? null,
        category: item.category,
        unit: item.unit,
        location_id: item.location_id,
        vendor_id: vendor_id, // Link to vendor
        status: 'approved',
        origin_type: 'procurement',
        origin_reference: input.inspection_id,
      })
      .select()
      .single()
    if (pinErr) throw new Error(`PIN creation: ${pinErr.message}`)

    // 2. Create receipt transaction
    const { error: txErr } = await sb.from('inventory_transactions').insert({
      pin_id: pin.id,
      transaction_type: 'receipt',
      quantity: item.quantity,
      quantity_before: 0, // new PIN, always starts at 0
      quantity_after: item.quantity,
      reference_type: 'delivery',
      reference_id: input.delivery_id,
      location_id: item.location_id,
      unit_cost: item.unit_cost ?? null,
      notes: `Intake from delivery — QC inspection ${input.inspection_id}`,
      actor_id: operatorId,
    })
    if (txErr) throw new Error(`Transaction: ${txErr.message}`)

    createdPins.push({ ...pin, initial_stock: item.quantity })
  }

  // Update delivery status to closed (fully received and accepted into inventory)
  await sb.from('deliveries').update({ status: 'closed' }).eq('id', input.delivery_id)

  return createdPins
}

/**
 * Apply a signed stock adjustment to an existing PIN.
 * Positive quantity = stock increase; negative = stock decrease.
 */
export async function dbAdjustStock(
  input: AdjustStockInput,
  operatorId: string
) {
  const sb = await createClient()
  const currentStock = await getCurrentStock(sb, input.pin_id)
  const newStock = currentStock + input.quantity
  if (newStock < 0) throw new Error('Adjustment would result in negative stock')

  const { error } = await sb.from('inventory_transactions').insert({
    pin_id: input.pin_id,
    transaction_type: 'adjustment',
    quantity: input.quantity,
    quantity_before: currentStock,
    quantity_after: newStock,
    reference_type: 'manual',
    location_id: input.location_id ?? null,
    unit_cost: input.unit_cost ?? null,
    notes: input.reason,
    actor_id: operatorId,
  })
  if (error) throw new Error(error.message)

  return { previous: currentStock, current: newStock }
}

/**
 * Transfer a quantity of a PIN to a new store location.
 * Updates the PIN's location_id and records a transfer transaction.
 * Note: transfer does not change the net stock level.
 */
export async function dbTransferPin(
  input: TransferPinInput,
  operatorId: string
) {
  const sb = await createClient()
  const currentStock = await getCurrentStock(sb, input.pin_id)
  if (currentStock < input.quantity)
    throw new Error('Insufficient stock for transfer')

  // Update PIN location
  const { error: locErr } = await sb
    .from('inventory_pins')
    .update({ location_id: input.to_location_id })
    .eq('id', input.pin_id)
  if (locErr) throw new Error(locErr.message)

  // Record transfer transaction (neutral quantity — location change only)
  const { error: txErr } = await sb.from('inventory_transactions').insert({
    pin_id: input.pin_id,
    transaction_type: 'transfer',
    quantity: input.quantity,
    quantity_before: currentStock,
    quantity_after: currentStock, // stock level unchanged
    reference_type: 'transfer',
    location_id: input.to_location_id,
    notes: input.notes ?? `Transfer from location ${input.from_location_id}`,
    actor_id: operatorId,
  })
  if (txErr) throw new Error(txErr.message)
}

/**
 * Write off a quantity as scrap. If stock reaches 0, marks the PIN as scrapped.
 */
export async function dbScrapPin(
  pinId: string,
  quantity: number,
  reason: string,
  operatorId: string
) {
  const sb = await createClient()
  const currentStock = await getCurrentStock(sb, pinId)
  if (currentStock < quantity)
    throw new Error('Scrap quantity exceeds available stock')
  const newStock = currentStock - quantity

  const { error: txErr } = await sb.from('inventory_transactions').insert({
    pin_id: pinId,
    transaction_type: 'write_off',
    quantity: -quantity,
    quantity_before: currentStock,
    quantity_after: newStock,
    reference_type: 'scrap',
    notes: reason,
    actor_id: operatorId,
  })
  if (txErr) throw new Error(txErr.message)

  // If fully scrapped, update PIN status
  if (newStock === 0) {
    await sb.from('inventory_pins').update({ status: 'scrapped' }).eq('id', pinId)
  }

  return { previous: currentStock, current: newStock }
}

/**
 * Put a PIN on hold so it cannot be issued.
 */
export async function dbHoldPin(pinId: string, notes: string): Promise<void> {
  const sb = await createClient()
  const { error } = await sb
    .from('inventory_pins')
    .update({ status: 'on_hold' })
    .eq('id', pinId)
  if (error) throw new Error(error.message)
}

/**
 * Release a PIN from hold back to approved status.
 */
export async function dbReleaseHold(pinId: string): Promise<void> {
  const sb = await createClient()
  const { error } = await sb
    .from('inventory_pins')
    .update({ status: 'approved' })
    .eq('id', pinId)
  if (error) throw new Error(error.message)
}
/**
 * Automated issuance from requirement.
 * Creates material_issues and reduces stock for each linked PIN.
 */
export async function dbIssueItemsFromRequirement(requirementId: string, actorId: string) {
  const sb = await createClient()
  
  // 1. Get requirement items linked to inventory
  const { data: items, error: itemsErr } = await sb
    .from('requirement_items')
    .select('*, requirements:requirements(vessel_id, requested_by, ref_number)')
    .eq('requirement_id', requirementId)
    .not('inventory_pin_id', 'is', null)
    .eq('item_request_type', 'to_release_from_inventory')

  if (itemsErr) throw new Error(itemsErr.message)
  if (!items || items.length === 0) return

  for (const item of items) {
    const pinId = item.inventory_pin_id!
    const qty = Number(item.quantity)
    const req = item.requirements as any

    // Safety check: prevent duplicate issues for the same requirement_item
    const { data: existingIssue } = await sb
      .from('material_issues')
      .select('id')
      .eq('requirement_item_id', item.id)
      .single()

    if (existingIssue) {
      console.warn(`Issue already exists for requirement_item ${item.id}, skipping`)
      continue
    }

    const currentStock = await getCurrentStock(sb, pinId)
    if (currentStock < qty) {
      throw new Error(
        `Insufficient stock for "${item.description}" — requested ${qty}, available ${currentStock}`
      )
    }

    // 2. Create Material Issue record in 'issued' state (PM already approved)
    const { data: issue, error: issueErr } = await sb
      .from('material_issues')
      .insert({
        pin_id: pinId,
        issued_to: req.requested_by,
        vessel_id: req.vessel_id ?? null,
        quantity: qty,
        unit: item.unit,
        status: 'issued',
        purpose: `${req.ref_number} · Line ${item.line_number} — ${item.description}`,
        approved_by: actorId,
        approved_at: new Date().toISOString(),
        issued_by: actorId,
        issued_at: new Date().toISOString(),
        quantity_returned: 0,
        // Traceability: link back to requirement and specific line item
        requirement_id: requirementId,
        requirement_item_id: item.id,
      })
      .select()
      .single()

    if (issueErr) throw new Error(`Material Issue creation: ${issueErr.message}`)

    // 3. Record issuance transaction (NEGATIVE quantity = stock OUT)
    // CRITICAL: Make absolutely sure we're recording a negative quantity
    const deductionQty = Math.abs(qty) * -1  // Force negative: -(absolute value)
    const newStockAfterIssue = currentStock + deductionQty  // currentStock + (-qty) = subtract

    if (newStockAfterIssue < 0) {
      throw new Error(`Stock went negative after release — logic error, contact support`)
    }

    const { error: txErr } = await sb.from('inventory_transactions').insert({
      pin_id: pinId,
      transaction_type: 'issue',
      quantity: deductionQty,  // MUST be negative
      quantity_before: currentStock,
      quantity_after: newStockAfterIssue,
      reference_type: 'issue',
      reference_id: issue.id,
      notes: `Released via ${req.ref_number} — approved by store`,
      actor_id: actorId,
    })
    if (txErr) throw new Error(`Stock transaction error: ${txErr.message}`)
  }
}
